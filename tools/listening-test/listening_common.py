"""Shared helpers of the MT / TTS listening-test builders (make_mt_test.py, make_tts_test.py).

A test folder is what friends get (zip ``test/``): ``index.html`` (a copy of mt-ab.html or
tts-listen.html), ``manifest.json`` and ``manifest.js`` (the same manifest as a script, so the page
works from file:// without fetch), plus ``audio/`` for TTS. ``key.json`` (which system is which) is
written next to ``test/`` and stays with the organizer.
"""

from __future__ import annotations

import hashlib
import json
import os
import random
import secrets
import shutil
import time

HERE = os.path.dirname(os.path.abspath(__file__))


def new_test_id() -> str:
    """16 hex characters from the OS's secure random source (never derived from the seed)."""
    return secrets.token_hex(8)


def rng_for(seed: int | None) -> tuple[random.Random, int]:
    seed = seed if seed is not None else secrets.randbits(63)
    return random.Random(seed), seed


def ranked(items, seed: int, *parts):
    """``items`` ordered by sha256(seed | parts | item key) (deterministic sampling)."""
    def key(x):
        k = x if isinstance(x, str) else json.dumps(x, sort_keys=True, ensure_ascii=False)
        return hashlib.sha256("|".join([str(seed), *map(str, parts), k]).encode("utf-8")).hexdigest()
    return sorted(items, key=key)


def write_test(out: str, page: str, manifest: dict, key: dict) -> str:
    """Write ``out/test/{index.html, manifest.json, manifest.js}`` and ``out/key.json``; returns the
    test folder."""
    test_dir = os.path.join(out, "test")
    os.makedirs(test_dir, exist_ok=True)
    shutil.copyfile(os.path.join(HERE, page), os.path.join(test_dir, "index.html"))
    text = json.dumps(manifest, ensure_ascii=False, indent=1)
    with open(os.path.join(test_dir, "manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text + "\n")
    with open(os.path.join(test_dir, "manifest.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/listening-test; loaded by index.html (works from file://).\n")
        f.write("window.SIGIL_LISTENING_MANIFEST = " + text + ";\n")
    key = dict(key, created_unix_ms=int(time.time() * 1000))
    with open(os.path.join(out, "key.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(key, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return test_dir
