/// The LAN rules in force (from [`LanAccessSettings`]).
#[derive(Clone, PartialEq, Eq)]
pub struct LanPolicy {
    pub mode: BindMode,
    /// Normalized token; `None` until the host has one (then no other machine gets in, unless
    /// legacy is on).
    token: Option<String>,
    pub legacy_no_token: bool,
}

impl fmt::Debug for LanPolicy {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("LanPolicy")
            .field("mode", &self.mode)
            .field("token_set", &self.token.is_some())
            .field("legacy_no_token", &self.legacy_no_token)
            .finish()
    }
}

impl Default for LanPolicy {
    fn default() -> Self {
        Self::from_settings(&LanAccessSettings::default())
    }
}

impl LanPolicy {
    /// A malformed token counts as none (the host regenerates it).
    pub fn from_settings(settings: &LanAccessSettings) -> Self {
        Self {
            mode: settings.mode,
            token: normalize_token(&settings.token),
            legacy_no_token: settings.legacy_no_token,
        }
    }

    pub fn token_set(&self) -> bool {
        self.token.is_some()
    }
}

/// Where a connection comes from, as far as the token is concerned.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Locality {
    /// A process on this PC, connected directly.
    ThisMachine,
    /// Another machine, an unknown peer, or anything that came through a reverse proxy.
    Remote,
}

pub fn locality(info: &ConnInfo, machine: &dyn LocalMachine) -> Locality {
    match info.remote {
        Some(addr) if !info.forwarded && machine.is_this_machine(addr.ip()) => Locality::ThisMachine,
        _ => Locality::Remote,
    }
}

/// Why the LAN rules let a connection in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LanGrant {
    /// Same PC: never needs the token.
    ThisMachine,
    /// Another machine with the right token.
    Token,
    /// Another machine without it, because `legacyNoToken` is on.
    Legacy,
}

/// Why the LAN rules refused a connection.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum LanRejected {
    /// `lanAccess.mode` is `localhost`.
    LanDisabled,
    /// Another machine without a token.
    MissingToken,
    /// Another machine with a wrong or malformed token (or none is set up yet).
    InvalidToken,
}

impl LanRejected {
    /// WebSocket close code and reason sent after the upgrade.
    pub fn close_frame(self) -> (u16, &'static str) {
        match self {
            LanRejected::LanDisabled => (CLOSE_LAN_DISABLED, "lan_disabled"),
            LanRejected::MissingToken => (CLOSE_LAN_UNAUTHORIZED, "missing_token"),
            LanRejected::InvalidToken => (CLOSE_LAN_UNAUTHORIZED, "invalid_token"),
        }
    }
}

impl fmt::Display for LanRejected {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            LanRejected::LanDisabled => "LAN access is set to this PC only",
            LanRejected::MissingToken => "no LAN token from another machine",
            LanRejected::InvalidToken => "wrong LAN token from another machine",
        })
    }
}

/// The LAN decision for one connection. Pure.
pub fn evaluate_lan(policy: &LanPolicy, locality: Locality, presented: Option<&str>) -> Result<LanGrant, LanRejected> {
    if locality == Locality::ThisMachine {
        return Ok(LanGrant::ThisMachine);
    }
    if policy.mode == BindMode::Localhost {
        return Err(LanRejected::LanDisabled);
    }
    let presented = presented.filter(|p| !p.trim().is_empty());
    if let (Some(expected), Some(p)) = (policy.token.as_deref(), presented) {
        if tokens_match(expected, p) {
            return Ok(LanGrant::Token);
        }
    }
    if policy.legacy_no_token {
        return Ok(LanGrant::Legacy);
    }
    Err(if presented.is_some() {
        LanRejected::InvalidToken
    } else {
        LanRejected::MissingToken
    })
}

