/// How the Origin rules let a connection in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OriginGrant {
    Allowed(Allowed),
    /// No `Origin` header from another machine (a non-browser tool): allowed only with the token.
    NoOriginWithToken,
}

/// Why a connection was let in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Grant {
    pub origin: OriginGrant,
    pub lan: LanGrant,
}

/// Why a connection was refused (or closed later).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Refusal {
    /// Stage 1: `403` before the upgrade (or close 1008 when revoked).
    Origin(Rejected),
    /// Stage 2: upgrade, then close 4401 / 4403.
    Lan(LanRejected),
}

impl Serialize for Refusal {
    /// One flat reason string: `foreign_origin`, …, `missing_token`, `invalid_token`, `lan_disabled`.
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        match self {
            Refusal::Origin(r) => r.serialize(serializer),
            Refusal::Lan(r) => r.serialize(serializer),
        }
    }
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Refusal::Origin(r) => r.fmt(f),
            Refusal::Lan(r) => r.fmt(f),
        }
    }
}

/// A refused or revoked connection, as logged and emitted to the UI (`web:origin_rejected`).
#[derive(Clone, Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct AccessRejection {
    /// `pubsub` or `peer`.
    pub route: String,
    /// The `Origin` value (truncated), or `None` when absent.
    pub origin: Option<String>,
    /// Peer IP address, if known.
    pub remote: Option<String>,
    pub reason: Refusal,
}

type RejectionNotifier = Box<dyn Fn(&AccessRejection) + Send + Sync>;

/// The access check for the WebSocket routes: Origin allow-list (stage 1) plus LAN token and
/// mode (stage 2), refusal reporting, and the change notifications that revoke connections.
pub struct AccessGuard {
    origin: OriginGuard,
    lan: watch::Sender<LanPolicy>,
    notifier: Mutex<Option<RejectionNotifier>>,
    last_notice: Mutex<HashMap<String, Instant>>,
}

impl AccessGuard {
    pub fn new(origin: OriginGuard, policy: LanPolicy) -> Self {
        Self {
            origin,
            lan: watch::Sender::new(policy),
            notifier: Mutex::new(None),
            last_notice: Mutex::new(HashMap::new()),
        }
    }

    /// The Origin allow-list and its kill switch.
    pub fn origin(&self) -> &OriginGuard {
        &self.origin
    }

    /// The LAN rules in force.
    pub fn lan_policy(&self) -> LanPolicy {
        self.lan.borrow().clone()
    }

    /// Replace the LAN rules. Connections the new rules refuse close themselves. Returns whether
    /// anything changed.
    pub fn set_lan_policy(&self, policy: LanPolicy) -> bool {
        self.lan.send_if_modified(|current| {
            if *current == policy {
                return false;
            }
            *current = policy;
            true
        })
    }

    /// Install a freshly generated token (keeps mode and legacy).
    pub fn set_token(&self, token: String) {
        let mut policy = self.lan_policy();
        policy.token = normalize_token(&token);
        self.set_lan_policy(policy);
    }

    /// Called (throttled) for every refused or revoked connection; used to emit
    /// `web:origin_rejected`.
    pub fn set_notifier(&self, notifier: impl Fn(&AccessRejection) + Send + Sync + 'static) {
        *self.notifier.lock().unwrap_or_else(PoisonError::into_inner) = Some(Box::new(notifier));
    }

    /// The decision for one connection under `policy`, without reporting.
    fn decide(&self, info: &ConnInfo, presented: Option<&str>, policy: &LanPolicy) -> Result<Grant, Refusal> {
        let lan = evaluate_lan(policy, locality(info, self.origin.machine()), presented);
        let origin = match self.origin.verdict(info) {
            Ok(allowed) => OriginGrant::Allowed(allowed),
            // A non-browser tool on another machine has no Origin to check; the token is what
            // authenticates it (legacy mode keeps stage 1's refusal).
            Err(Rejected::MissingOriginRemote) if lan == Ok(LanGrant::Token) => OriginGrant::NoOriginWithToken,
            Err(rejected) => return Err(Refusal::Origin(rejected)),
        };
        let lan = lan.map_err(Refusal::Lan)?;
        Ok(Grant { origin, lan })
    }

    /// The current decision for one connection, without reporting.
    pub fn check(&self, info: &ConnInfo, presented: Option<&str>) -> Result<Grant, Refusal> {
        self.decide(info, presented, &self.lan.borrow())
    }

    /// Decide one handshake on `route`. Refusals are logged and reported (throttled). An admitted
    /// connection gets an [`Access`] whose [`revoked`](Access::revoked) completes when a later
    /// change of the rules refuses it.
    pub fn admit(&self, info: ConnInfo, presented: Option<String>, route: &'static str) -> Result<Access, Refusal> {
        // Subscribe before deciding, so a change right after this handshake is still seen.
        let origin_rx = self.origin.subscribe();
        let lan_rx = self.lan.subscribe();
        match self.check(&info, presented.as_deref()) {
            Ok(grant) => {
                tracing::debug!(
                    target: "sigil::web",
                    "/{route}: accepted {grant:?} (Origin {:?}, peer {:?})",
                    info.origin.for_report(),
                    info.remote.map(|a| a.ip()),
                );
                Ok(Access {
                    grant,
                    route,
                    info,
                    presented,
                    origin_rx,
                    lan_rx,
                })
            }
            Err(reason) => {
                self.report(rejection(route, &info, reason), "refused WebSocket upgrade on");
                Err(reason)
            }
        }
    }

    /// Report a connection closed because the rules changed (logged, throttled like a refusal).
    pub fn report_revoked(&self, rejection: AccessRejection) {
        self.report(rejection, "closing a connection the new rules refuse on");
    }

    fn report(&self, rejection: AccessRejection, what: &str) {
        let key = match (&rejection.reason, &rejection.origin) {
            (Refusal::Origin(_), Some(origin)) => format!("o:{origin}"),
            (Refusal::Origin(_), None) => format!("r:{}", rejection.remote.as_deref().unwrap_or("?")),
            (Refusal::Lan(_), _) => format!("l:{}", rejection.remote.as_deref().unwrap_or("?")),
        };
        {
            let mut seen = self
                .last_notice
                .lock()
                .unwrap_or_else(PoisonError::into_inner);
            let now = Instant::now();
            if seen
                .get(&key)
                .is_some_and(|at| now.duration_since(*at) < REJECTION_NOTICE_INTERVAL)
            {
                return;
            }
            if seen.len() >= REJECTION_NOTICE_MAX_KEYS {
                seen.retain(|_, at| now.duration_since(*at) < REJECTION_NOTICE_INTERVAL);
                if seen.len() >= REJECTION_NOTICE_MAX_KEYS {
                    // Flooded with distinct origins: stay quiet until the window passes.
                    return;
                }
            }
            seen.insert(key, now);
        }
        let hint = match rejection.reason {
            Refusal::Origin(_) => format!(
                "Set lanOriginCheck=false or {}=0 only if this is a trusted client.",
                origin::ORIGIN_CHECK_ENV
            ),
            Refusal::Lan(LanRejected::LanDisabled) => "LAN access is set to this PC only.".to_string(),
            Refusal::Lan(_) => "Copy the LAN link again from Settings → LAN access on the device that is refused.".to_string(),
        };
        tracing::warn!(
            target: "sigil::web",
            "{what} /{}: {} (Origin {:?}, peer {}). {hint}",
            rejection.route,
            rejection.reason,
            rejection.origin,
            rejection.remote.as_deref().unwrap_or("unknown"),
        );
        if let Some(notify) = self
            .notifier
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .as_ref()
        {
            notify(&rejection);
        }
    }
}

fn rejection(route: &str, info: &ConnInfo, reason: Refusal) -> AccessRejection {
    AccessRejection {
        route: route.to_string(),
        origin: info.origin.for_report(),
        remote: info.remote.map(|a| a.ip().to_string()),
        reason,
    }
}

/// A connection [`AccessGuard::admit`] let in. Holds what is needed to re-check it.
pub struct Access {
    pub grant: Grant,
    route: &'static str,
    info: ConnInfo,
    /// Kept to re-check after a token change; never logged.
    presented: Option<String>,
    origin_rx: watch::Receiver<bool>,
    lan_rx: watch::Receiver<LanPolicy>,
}

impl fmt::Debug for Access {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Access")
            .field("grant", &self.grant)
            .field("route", &self.route)
            .field("remote", &self.info.remote)
            .finish_non_exhaustive()
    }
}

impl Access {
    /// Completes, with the refusal to report, once the Origin switch or the LAN rules change so
    /// that this connection would be refused now; never completes otherwise (also not when the
    /// guard is gone). Cancel-safe (use in a `select!` loop): a change already made since the last
    /// call is seen at once.
    pub async fn revoked(&mut self, guard: &AccessGuard) -> AccessRejection {
        loop {
            tokio::select! {
                changed = self.origin_rx.changed() => {
                    if changed.is_err() {
                        std::future::pending::<()>().await;
                    }
                }
                changed = self.lan_rx.changed() => {
                    if changed.is_err() {
                        std::future::pending::<()>().await;
                    }
                }
            }
            self.origin_rx.borrow_and_update();
            let policy = self.lan_rx.borrow_and_update().clone();
            if let Err(reason) = guard.decide(&self.info, self.presented.as_deref(), &policy) {
                return rejection(self.route, &self.info, reason);
            }
        }
    }
}

