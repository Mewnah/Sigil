    #[test]
    fn other_machines_need_the_token() {
        let p = policy(BindMode::Lan, TOKEN, false);
        let r = Locality::Remote;
        assert_eq!(evaluate_lan(&p, r, Some(TOKEN)), Ok(LanGrant::Token));
        assert_eq!(evaluate_lan(&p, r, Some(&TOKEN.to_uppercase())), Ok(LanGrant::Token));
        assert_eq!(evaluate_lan(&p, r, None), Err(LanRejected::MissingToken));
        assert_eq!(evaluate_lan(&p, r, Some("")), Err(LanRejected::MissingToken));
        assert_eq!(evaluate_lan(&p, r, Some("  ")), Err(LanRejected::MissingToken));
        assert_eq!(evaluate_lan(&p, r, Some("0123456789abcdefghjkmnpqrt")), Err(LanRejected::InvalidToken));
        assert_eq!(evaluate_lan(&p, r, Some("garbage")), Err(LanRejected::InvalidToken));

        // No token generated yet: nobody from outside gets in.
        let none = policy(BindMode::Lan, "", false);
        assert_eq!(evaluate_lan(&none, r, None), Err(LanRejected::MissingToken));
        assert_eq!(evaluate_lan(&none, r, Some(TOKEN)), Err(LanRejected::InvalidToken));

        // Legacy: in without a token, but a right token still counts as a token.
        let legacy = policy(BindMode::Lan, TOKEN, true);
        assert_eq!(evaluate_lan(&legacy, r, None), Ok(LanGrant::Legacy));
        assert_eq!(evaluate_lan(&legacy, r, Some("wrong")), Ok(LanGrant::Legacy));
        assert_eq!(evaluate_lan(&legacy, r, Some(TOKEN)), Ok(LanGrant::Token));

        // This PC only: even the right token (or legacy) is refused.
        let local = policy(BindMode::Localhost, TOKEN, true);
        assert_eq!(evaluate_lan(&local, r, Some(TOKEN)), Err(LanRejected::LanDisabled));
        assert_eq!(evaluate_lan(&local, r, None), Err(LanRejected::LanDisabled));
    }

