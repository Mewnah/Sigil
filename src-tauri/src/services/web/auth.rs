    fn conn(origin: Option<&str>, remote: [u8; 4]) -> ConnInfo {
        let header = origin.map_or(OriginHeader::Absent, |o| OriginHeader::Present(o.to_string()));
        ConnInfo::direct(header, Some(SocketAddr::from((remote, 50000))))
    }

    fn proxied(origin: Option<&str>, remote: [u8; 4]) -> ConnInfo {
        ConnInfo {
            forwarded: true,
            ..conn(origin, remote)
        }
    }

