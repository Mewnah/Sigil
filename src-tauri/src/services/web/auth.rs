    #[test]
    fn refusals_are_reported_once_per_window() {
        let g = guard(policy(BindMode::Lan, TOKEN, false));
        let seen = Arc::new(Mutex::new(Vec::<AccessRejection>::new()));
        let sink = seen.clone();
        g.set_notifier(move |r| sink.lock().unwrap().push(r.clone()));

        for _ in 0..5 {
            let _ = g.admit(conn(Some("https://evil.example"), LOOPBACK), None, "pubsub");
        }
        let _ = g.admit(conn(Some("https://other.example"), LOOPBACK), None, "peer");
        let _ = g.admit(conn(Some("http://localhost:3030"), LOOPBACK), None, "peer");
        let _ = g.admit(conn(None, OTHER_PC), None, "pubsub");
        for _ in 0..3 {
            let _ = g.admit(conn(PAGE, [192, 168, 1, 80]), Some("wrong".into()), "peer");
        }

        let seen = seen.lock().unwrap();
        assert_eq!(seen.len(), 4, "{seen:?}");
        assert_eq!(
            seen[0],
            AccessRejection {
                route: "pubsub".into(),
                origin: Some("https://evil.example".into()),
                remote: Some("127.0.0.1".into()),
                reason: Refusal::Origin(Rejected::ForeignOrigin),
            }
        );
        assert_eq!(seen[1].origin.as_deref(), Some("https://other.example"));
        assert_eq!(seen[2].reason, Refusal::Origin(Rejected::MissingOriginRemote));
        assert_eq!(seen[2].origin, None);
        assert_eq!(seen[3].reason, Refusal::Lan(LanRejected::InvalidToken));
        assert_eq!(seen[3].remote.as_deref(), Some("192.168.1.80"));
        // The event never carries a token.
        let json = serde_json::to_string(&seen[3]).unwrap();
        assert!(!json.contains("wrong"), "{json}");
        assert!(json.contains(r#""reason":"invalid_token""#), "{json}");
    }

