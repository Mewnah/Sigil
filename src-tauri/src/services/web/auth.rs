//! LAN security stage 2 (P6-D): a persistent token for clients on other machines, the bind mode,
//! and the single access decision for the `/pubsub` and `/peer` WebSocket routes.
//!
//! Stage 1 ([`super::origin`]) stops web pages from hijacking the sockets; this stage authenticates
//! the clients that are not on this PC. The root setting `lanAccess {mode, token, legacyNoToken}`
//! (src/core/schema.ts) drives it:
//!
//! | Client | Needs the token? |
//! |---|---|
//! | Anything on this PC: the host webview, OBS here, `mic.html`, `obs-captions.html`, local tools | No (loopback or this PC's own address) |
//! | `/client`, captions page, phone or OBS on another PC | Yes: `?token=` in the page URL; `/client` passes it as the PeerJS `key` |
//! | Link apps from another Sigil | Yes: the remote token, sent as `?token=` on `/pubsub` |
//! | A connection through a reverse proxy or tunnel (forwarding headers) | Yes, even when the proxy is on this PC |
//!
//! - **Token**: 26 symbols of Crockford base32 (130 bits) from the OS CSPRNG, generated by
//!   [`generate_token`] when the host has none (first start) or on **Regenerate**. It is persisted by
//!   the host in the settings file (so saved OBS links survive restarts) and read from there at
//!   startup, so the server enforces it before the webview loads. Presented tokens are normalized
//!   ([`normalize_token`]: case, `-` and spaces, `o`/`i`/`l` typos) and compared in constant time.
//!   The token is never logged and never part of a status or event.
//! - **Where it travels**: `?token=` on `/pubsub`, `?key=` on `/peer` (PeerJS sends its own random
//!   `token` parameter there, which is ignored). Pages carry it as `?token=` in their own URL.
//! - **Mode** ([`BindMode`]): `lan` binds `0.0.0.0` (as before; other machines need the token),
//!   `localhost` binds `127.0.0.1` only and also refuses any non-local peer here, so connections
//!   from before a switch are closed at once.
//! - **Legacy** (`legacyNoToken`, default off, shown with a caution label): other machines get in
//!   without the token, as in stage 1 (Origin allow-list only).
//! - **Refusals** happen after the WebSocket upgrade, with close code [`CLOSE_LAN_UNAUTHORIZED`]
//!   (4401, token missing or wrong) or [`CLOSE_LAN_DISABLED`] (4403, this PC only), so pages and
//!   Link apps can say why (`/peer` first sends PeerJS's `INVALID-KEY`). Origin refusals stay a plain
//!   `403` before the upgrade. Every refusal is logged and reported (`web:origin_rejected`,
//!   throttled per origin or peer address).
//! - **Revocation**: every admitted connection re-checks itself whenever the Origin switch or the
//!   LAN policy changes ([`Access::revoked`]): a new token disconnects LAN clients still on the old
//!   one, switching to `localhost` disconnects every other machine, turning legacy off disconnects
//!   the token-less ones, and turning the Origin check back on disconnects foreign pages. For a
//!   `/client` mirror this covers its WebRTC data channel too, not only the `/peer` socket: the
//!   signaling server sends PeerJS `LEAVE` for every departed peer to the peers it signaled, and the
//!   host closes its connections with it (see [`super::peer`]).

