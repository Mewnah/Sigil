/// A fresh LAN token from the operating system's CSPRNG.
pub fn generate_token() -> Result<String, String> {
    let mut bytes = [0u8; TOKEN_LEN];
    crate::services::process_host::spawn::os_random(&mut bytes)?;
    Ok(token_from_random_bytes(&bytes))
}

/// Map random bytes to token symbols: the low 5 bits of each byte (256 is a multiple of 32, so
/// every symbol is equally likely).
fn token_from_random_bytes(bytes: &[u8; TOKEN_LEN]) -> String {
    bytes
        .iter()
        .map(|b| TOKEN_ALPHABET[usize::from(b & 31)] as char)
        .collect()
}

/// The canonical form of a typed or presented token, or `None` if it is not one: ASCII case is
/// ignored, `-`, spaces and tabs are skipped (grouping), and the Crockford look-alikes `o` → `0`,
/// `i` / `l` → `1` are mapped. The TS twin is `normalizeLanToken` in
/// src/shared/services/peer/lanAccess.ts (same vectors in both test suites).
pub fn normalize_token(raw: &str) -> Option<String> {
    if raw.len() > MAX_PRESENTED_TOKEN_LEN {
        return None;
    }
    let mut out = String::with_capacity(TOKEN_LEN);
    for c in raw.chars() {
        let c = match c.to_ascii_lowercase() {
            '-' | ' ' | '\t' => continue,
            'o' => '0',
            'i' | 'l' => '1',
            c => c,
        };
        if !c.is_ascii() || !TOKEN_ALPHABET.contains(&(c as u8)) {
            return None;
        }
        out.push(c);
    }
    (out.len() == TOKEN_LEN).then_some(out)
}

/// Compare without an early exit, so response timing says nothing about how much of a guess was
/// right.
fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let diff = a.iter().zip(b).fold(0u8, |acc, (x, y)| acc | (x ^ y));
    std::hint::black_box(diff) == 0
}

/// Whether `presented` is the token `expected` (already normalized).
pub fn tokens_match(expected: &str, presented: &str) -> bool {
    normalize_token(presented).is_some_and(|p| constant_time_eq(expected.as_bytes(), p.as_bytes()))
}

