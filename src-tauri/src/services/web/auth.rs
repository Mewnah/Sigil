/// Length of a LAN token in symbols (5 bits each: 130 bits).
pub const TOKEN_LEN: usize = 26;

/// Crockford base32, lower case: no `i`, `l`, `o`, `u`, so a token read aloud or typed from a
/// screen is unambiguous.
const TOKEN_ALPHABET: &[u8; 32] = b"0123456789abcdefghjkmnpqrstvwxyz";

/// Longest presented token we look at (anything longer is refused without further work).
pub const MAX_PRESENTED_TOKEN_LEN: usize = 128;

/// WebSocket close code (application range) after the upgrade: the LAN token is missing or wrong.
pub const CLOSE_LAN_UNAUTHORIZED: u16 = 4401;

/// WebSocket close code (application range) after the upgrade: this server accepts only clients on
/// its own PC (`lanAccess.mode = "localhost"`).
pub const CLOSE_LAN_DISABLED: u16 = 4403;

/// A refused or revoked connection is logged and reported at most once per this interval per
/// origin (or per peer address for origin-less and LAN refusals).
const REJECTION_NOTICE_INTERVAL: Duration = Duration::from_secs(60);

/// Bound on the rejection throttle map (an attacker can vary the Origin freely).
const REJECTION_NOTICE_MAX_KEYS: usize = 256;

