    #[test]
    fn combined_decisions() {
        let g = guard(policy(BindMode::Lan, TOKEN, false));
        // The client matrix.
        let host = g.check(&conn(TAURI, LOOPBACK), None).unwrap();
        assert_eq!(host.lan, LanGrant::ThisMachine);
        assert_eq!(host.origin, OriginGrant::Allowed(Allowed::TauriApp));
        let obs_here = g
            .check(&conn(Some("http://localhost:3030"), LOOPBACK), None)
            .unwrap();
        assert_eq!(obs_here.lan, LanGrant::ThisMachine);
        assert_eq!(g.check(&conn(None, LOOPBACK), None).unwrap().lan, LanGrant::ThisMachine);
        let lan_client = g.check(&conn(PAGE, OTHER_PC), Some(TOKEN)).unwrap();
        assert_eq!(lan_client.lan, LanGrant::Token);
        let link_app = g.check(&conn(TAURI, OTHER_PC), Some(TOKEN)).unwrap();
        assert_eq!(link_app.origin, OriginGrant::Allowed(Allowed::TauriApp));
        assert_eq!(link_app.lan, LanGrant::Token);
        assert_eq!(
            g.check(&conn(PAGE, OTHER_PC), None),
            Err(Refusal::Lan(LanRejected::MissingToken))
        );
        assert_eq!(
            g.check(&conn(TAURI, OTHER_PC), Some("nope")),
            Err(Refusal::Lan(LanRejected::InvalidToken))
        );

        // A foreign origin is refused by stage 1 even with the right token.
        assert_eq!(
            g.check(&conn(Some("https://evil.example"), OTHER_PC), Some(TOKEN)),
            Err(Refusal::Origin(Rejected::ForeignOrigin))
        );
        // An origin-less tool on another machine gets in only with the token.
        assert_eq!(
            g.check(&conn(None, OTHER_PC), Some(TOKEN)).unwrap().origin,
            OriginGrant::NoOriginWithToken
        );
        assert_eq!(
            g.check(&conn(None, OTHER_PC), None),
            Err(Refusal::Origin(Rejected::MissingOriginRemote))
        );
        let legacy = guard(policy(BindMode::Lan, TOKEN, true));
        assert_eq!(
            legacy.check(&conn(None, OTHER_PC), None),
            Err(Refusal::Origin(Rejected::MissingOriginRemote)),
            "legacy keeps stage 1's refusal of origin-less LAN tools"
        );
        assert_eq!(legacy.check(&conn(PAGE, OTHER_PC), None).unwrap().lan, LanGrant::Legacy);

        // The Origin kill switch never disables the token.
        let no_origin_check = guard_with(false, policy(BindMode::Lan, TOKEN, false));
        assert_eq!(
            no_origin_check.check(&conn(Some("https://evil.example"), OTHER_PC), None),
            Err(Refusal::Lan(LanRejected::MissingToken))
        );
        assert_eq!(
            no_origin_check
                .check(&conn(Some("https://evil.example"), LOOPBACK), None)
                .unwrap()
                .origin,
            OriginGrant::Allowed(Allowed::CheckDisabled)
        );

        // A local reverse proxy does not get the same-PC exemption.
        assert_eq!(
            g.check(&proxied(Some("http://localhost:3030"), LOOPBACK), None),
            Err(Refusal::Lan(LanRejected::MissingToken))
        );
        assert!(g
            .check(&proxied(Some("http://localhost:3030"), LOOPBACK), Some(TOKEN))
            .is_ok());

        // This PC only.
        let local = guard(policy(BindMode::Localhost, TOKEN, false));
        assert_eq!(
            local.check(&conn(PAGE, OTHER_PC), Some(TOKEN)),
            Err(Refusal::Lan(LanRejected::LanDisabled))
        );
        assert!(local.check(&conn(TAURI, LOOPBACK), None).is_ok());
    }

