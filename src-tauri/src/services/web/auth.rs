/// `lanAccess.mode`: which interfaces the server listens on.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum BindMode {
    /// All IPv4 interfaces (`0.0.0.0`); other machines need the token.
    #[default]
    Lan,
    /// `127.0.0.1` only.
    Localhost,
}

impl BindMode {
    pub fn parse(value: &str) -> Option<Self> {
        match value {
            "lan" => Some(BindMode::Lan),
            "localhost" => Some(BindMode::Localhost),
            _ => None,
        }
    }

    /// The address this mode listens on.
    pub fn ip(self) -> IpAddr {
        match self {
            BindMode::Lan => IpAddr::V4(Ipv4Addr::UNSPECIFIED),
            BindMode::Localhost => IpAddr::V4(Ipv4Addr::LOCALHOST),
        }
    }

    pub fn socket_addr(self, port: u16) -> SocketAddr {
        SocketAddr::new(self.ip(), port)
    }

    pub fn as_str(self) -> &'static str {
        match self {
            BindMode::Lan => "lan",
            BindMode::Localhost => "localhost",
        }
    }
}

/// The root setting `lanAccess` (wire format of `plugin:web|set_lan_access`).
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct LanAccessSettings {
    pub mode: BindMode,
    /// "" until the host generated one.
    pub token: String,
    pub legacy_no_token: bool,
}

/// `lanAccess` from the host's persisted settings JSON, read the way the schema's `zSafe` would:
/// an unknown mode is `lan`, a non-string token is "", and only an explicit `true` enables legacy.
/// `None` when the bytes are not a JSON object.
pub fn lan_access_from_settings(bytes: &[u8]) -> Option<LanAccessSettings> {
    let value: serde_json::Value = serde_json::from_slice(bytes).ok()?;
    let root = value.as_object()?;
    let lan = root.get("lanAccess").and_then(|v| v.as_object());
    let field = |name: &str| lan.and_then(|o| o.get(name));
    Some(LanAccessSettings {
        mode: field("mode")
            .and_then(|v| v.as_str())
            .and_then(BindMode::parse)
            .unwrap_or_default(),
        token: field("token")
            .and_then(|v| v.as_str())
            .unwrap_or_default()
            .to_string(),
        legacy_no_token: matches!(field("legacyNoToken"), Some(serde_json::Value::Bool(true))),
    })
}

/// `lanAccess` from `<app_data>/user/settings` (or its backup).
pub fn persisted_lan_access(app_data_dir: &Path) -> Option<LanAccessSettings> {
    origin::read_persisted_settings(app_data_dir, lan_access_from_settings)
}

